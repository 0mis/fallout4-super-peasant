"""STEP 7.6: cape_bind.json (written by the One Punch Man Blender build, opm\\build_opm.py) -> src/core/cape_model.gen.h.

    uv run --no-project python -I tools/gen_cape_model.py <cape_bind.json> <out.h>

Bone binds come from the exported NIF's own skin-to-bone transforms (inverted), so the runtime matches exactly what the
renderer binds; they are cross-checked against the Blender bone rest (|dt| < 0.01 u, |dR| < 1e-4).
"""
import json, sys, math

src, out = sys.argv[1], sys.argv[2]
d = json.load(open(src))

def inv(s2b):
    R = s2b["rotation"]; t = s2b["translation"]; s = s2b["scale"]
    RT = [[R[c][r] for c in range(3)] for r in range(3)]
    ti = [-(RT[r][0] * t[0] + RT[r][1] * t[1] + RT[r][2] * t[2]) / s for r in range(3)]
    return RT, ti, 1.0 / s

def model(name):
    m = d["bones_model"][name]
    return [[m[r][c] for c in range(3)] for r in range(3)], [m[0][3], m[1][3], m[2][3]]

def check(name, R, t):
    Rm, tm = model(name)
    dt = math.dist(t, tm); dR = max(abs(R[r][c] - Rm[r][c]) for r in range(3) for c in range(3))
    if dt > 0.01 or dR > 1e-4:
        raise SystemExit("bind mismatch %s dt=%.4f dR=%.6f" % (name, dt, dR))

def fmt(v): return "%.6f" % v
L = []
w = L.append
w("#pragma once")
w("// GENERATED by tools/gen_cape_model.py from %s - do not edit." % src.replace("\\", "/").split("/")[-1])
w("// STEP 7.6 cape bind data (FO4 model space of his armor NIF, game units).")
w("namespace sp::cape::model")
w("{")
PU, PV = d["PU"], d["PV"]
w("\tinline constexpr int kU = %d, kV = %d;" % (PU, PV))
w("\tinline constexpr double kRest[kV][kU][3] = {")
for j in range(PV):
    w("\t\t{ " + ", ".join("{ %s }" % ", ".join(fmt(x) for x in d["particles"][j][i]) for i in range(PU)) + " },")
w("\t};")
anchors = d["anchors"]
w("\tinline constexpr int kBones = %d;" % len(anchors))
w("\tinline constexpr const char* kBoneName[kBones] = { " + ", ".join('"%s"' % a["bone"] for a in anchors) + " };")
w("\tinline constexpr double kBoneU[kBones] = { " + ", ".join(fmt(a["u"]) for a in anchors) + " };")
w("\tinline constexpr double kBoneV[kBones] = { " + ", ".join(fmt(a["v"]) for a in anchors) + " };")
w("\tstruct Bind { double R[9]; double T[3]; };")
w("\tinline constexpr Bind kBoneBind[kBones] = {")
for a in anchors:
    R, t, s = inv(d["skin_to_bone"][a["bone"]]); check(a["bone"], R, t)
    w("\t\t{ { %s }, { %s } },  // %s" % (", ".join(fmt(R[r][c]) for r in range(3) for c in range(3)), ", ".join(fmt(x) for x in t), a["bone"]))
w("\t};")
R, t, s = inv(d["skin_to_bone"]["Chest"]); check("Chest", R, t)
w("\tinline constexpr Bind kChestBind = { { %s }, { %s } };" % (", ".join(fmt(R[r][c]) for r in range(3) for c in range(3)), ", ".join(fmt(x) for x in t)))
caps = []
for c in d["capsules"]:
    if c["bone"] == "Chest" and caps and caps[-1]["bone"] == "Chest" and "w" not in caps[-1]:
        a = caps[-1]   # the two side-by-side torso capsules -> one elliptic tube (half-width w)
        mid = lambda p, q: [(p[i] + q[i]) * 0.5 for i in range(3)]
        half = abs(c["p0"][0] - a["p0"][0]) * 0.5
        caps[-1] = {"bone": "Chest", "p0": mid(a["p0"], c["p0"]), "p1": mid(a["p1"], c["p1"]), "r": a["r"], "w": half + a["r"]}
    else:
        caps.append(dict(c))
w("\tstruct CapDef { const char* bone; Bind bind; double p0[3]; double p1[3]; double r; int oneSided; double w; };")
w("\tinline constexpr int kCaps = %d;" % len(caps))
w("\tinline constexpr CapDef kCap[kCaps] = {")
for c in caps:
    R, t = model(c["bone"])
    one = 1 if c["bone"] in ("Chest", "Pelvis", "SPINE1") else 0
    w("\t\t{ \"%s\", { { %s }, { %s } }, { %s }, { %s }, %s, %d, %s }," % (c["bone"], ", ".join(fmt(R[r][cc]) for r in range(3) for cc in range(3)), ", ".join(fmt(x) for x in t),
      ", ".join(fmt(x) for x in c["p0"]), ", ".join(fmt(x) for x in c["p1"]), fmt(c["r"]), one, fmt(c.get("w", 0.0))))
w("\t};")
w("}")
open(out, "w", newline="\n").write("\n".join(L) + "\n")
print("wrote", out, "bones", len(anchors), "caps", len(caps))
