#!/usr/bin/env python3
"""gen_body_model.py - OWNER: BODY.  Emits src/core/body_model.gen.h: the tabs_constants.json data the body sim reads,
as iterable constexpr tables (the same fields body_twin.py's SpecData reads, nothing else).

    uv run --no-project python -I tools/gen_body_model.py tools/tabs_constants.json src/core/body_model.gen.h

Floats are written with repr() so the C++ doubles equal the twin's doubles bit for bit.
"""
import json
import sys

RIG_NAMES = ["Head", "Hip", "Torso", "Arm_Left", "Elbow_Left", "Arm_Right", "Elbow_Right",
             "Leg_Left", "Knee_Left", "Leg_Right", "Knee_Right", "Fist_Left", "Fist_Right"]
MATS = ["BodyDefault", "Foot", "Slippery"]


def f(x):
    r = repr(float(x))
    if r == "inf":
        return "std::numeric_limits<double>::infinity()"
    if r == "-inf":
        return "-std::numeric_limits<double>::infinity()"
    return r


def arr(v):
    return "{ " + ", ".join(f(x) for x in v) + " }"


def curve_keys(c):
    if isinstance(c, dict) and "m_Curve" in c:
        return [(k["time"], k["value"], k["inSlope"], k["outSlope"]) for k in c["m_Curve"]]
    if isinstance(c, dict) and "keys" in c:
        return [tuple(k[:4]) for k in c["keys"]]
    return [tuple(k[:4]) for k in c]


class Out:
    def __init__(self):
        self.lines = []
        self.ncurve = 0

    def w(self, s=""):
        self.lines.append(s)

    def curve(self, c, name=None):
        keys = curve_keys(c)
        name = name or "kCurve%d" % self.ncurve
        self.ncurve += 1
        self.w("inline constexpr CurveKey %s_k[%d]{ %s };" % (name, max(1, len(keys)), ", ".join(
            "{ %s, %s, %s, %s }" % tuple(f(x) for x in k) for k in keys) if keys else "{}"))
        self.w("inline constexpr Curve %s{ %s_k, %d };" % (name, name, len(keys)))
        return name


def main():
    src, dst = sys.argv[1], sys.argv[2]
    with open(src, "r", encoding="utf-8") as fh:
        d = json.load(fh)
    o = Out()
    o.w("// GENERATED by tools/gen_body_model.py from tools/tabs_constants.json - do not edit. OWNER: BODY.")
    o.w("#pragma once")
    o.w("#include <array>")
    o.w("#include <limits>")
    o.w("namespace sp::body::gen")
    o.w("{")
    o.w("struct CurveKey { double t, v, in, out; };")
    o.w("struct Curve { const CurveKey* k; int n; };")
    o.w("enum Mat : int { kMatBodyDefault = 0, kMatFoot = 1, kMatSlippery = 2, kMatMap = 3 };")
    o.w("struct MatDef { double mu; int combine; };")
    mats = {m["m_Name"]: (m["dynamicFriction"], m["frictionCombine"]) for m in d["raw_physic_materials"].values()}
    o.w("inline constexpr MatDef kMats[3]{ %s };" % ", ".join("{ %s, %d }" % (f(mats[n][0]), mats[n][1]) for n in MATS))
    o.w("struct ColDef { int kind; std::array<double, 3> c; double r; double h; std::array<double, 3> axis; int mat; };"
        "  // kind 0 sphere, 1 capsule")
    o.w("struct JointDef { bool has; int connected; std::array<double, 3> anchor, connAnchor, axis, secondary; "
        "double k, c, low, high, ay, az; };")
    o.w("struct RigDef { double scale; std::array<double, 3> pos; std::array<double, 4> rot; double mass, drag, adrag; "
        "int nCol; ColDef col[2]; bool hasCom; std::array<double, 3> com; JointDef joint; };")
    rigs = d["raw_rigs"]
    assert [r["name"] for r in rigs] == RIG_NAMES[:11]
    o.w("inline constexpr RigDef kRigs[11]{")
    for r in rigs:
        cols = []
        for c in r["colliders"]:
            kind = 0 if c["kind"] == "SphereCollider" else 1
            h = c.get("height_scaled_s1", 0.0)
            ax = c.get("axis_rig_frame", (0.0, 1.0, 0.0))
            cols.append("{ %d, %s, %s, %s, %s, %d }" % (kind, arr(c["center_rig_frame_scaled_s1"]), f(c["radius_scaled_s1"]),
                                                       f(h), arr(ax), MATS.index(c["material"])))
        assert 1 <= len(cols) <= 2
        while len(cols) < 2:
            cols.append("{}")
        com = r["children"].get("CenterOfMass")
        j = r.get("joint")
        if j:
            js = "{ true, %d, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s }" % (
                RIG_NAMES.index(j["connected_to"]), arr(j["anchor"]), arr(j["connected_anchor"]), arr(j["axis"]),
                arr(j["secondary_axis"]), f(j["angular_x_drive_prefab"][0]), f(j["angular_x_drive_prefab"][1]),
                f(j["low_angular_x"]), f(j["high_angular_x"]), f(j["angular_y"]), f(j["angular_z"]))
        else:
            js = "{}"
        o.w("    { %s, %s, %s, %s, %s, %s, %d, { %s }, %s, %s, %s },  // %s" % (
            f(r["local_scale"][0]), arr(r["local_pos_root_s1"]), arr(r["local_rot_xyzw"]), f(r["base_mass_kg"]),
            f(r["prefab_drag"]), f(r["prefab_angular_drag"]), len(r["colliders"]), ", ".join(cols),
            "true" if com is not None else "false", arr(com["local_pos"]) if com is not None else "{}", js, r["name"]))
    o.w("};")
    # fist
    fist = d["raw_fist_weapon"]
    rb = fist["rigidbody"]
    o.w("inline constexpr double kFistMass = %s, kFistDrag = %s, kFistAngDrag = %s;" % (f(rb["m_Mass"]), f(rb["m_Drag"]),
                                                                                       f(rb["m_AngularDrag"])))
    o.w("struct BoxDef { std::array<double, 3> he; std::array<double, 4> rot; std::array<double, 3> c; };")
    boxes = []
    for c in fist["colliders"]:
        he = [0.5 * c["size"][k] * c["local_scale"][k] for k in range(3)]
        rq = list(c["local_rot_xyzw"])
        neg = rq[3] < 0
        lp, ce = c["local_pos"], c["center"]
        cen = [lp[k] + ce[k] for k in range(3)]
        boxes.append((he, rq, neg, cen))
    o.w("inline constexpr int kFistBoxes = %d;" % len(boxes))
    # rot is stored raw (sign flip + normalize happen in C++ exactly like the twin)
    o.w("inline constexpr BoxDef kFistBox[%d]{ %s };" % (len(boxes), ", ".join(
        "{ %s, %s, %s }" % (arr(b[0]), arr([-x for x in b[1]] if b[2] else b[1]), arr(b[3])) for b in boxes)))
    g = fist["children"]
    o.w("inline constexpr std::array<double, 3> kForcePoint = %s;" % arr(g["ForcePoint"]["local_pos"]))
    o.w("inline constexpr std::array<double, 3> kGripPos[2]{ %s, %s };  // 0 left, 1 right" % (
        arr(g["LeftHand"]["local_pos"]), arr(g["RightHand"]["local_pos"])))
    o.w("inline constexpr std::array<double, 4> kGripRot[2]{ %s, %s };" % (
        arr(g["LeftHand"]["local_rot_xyzw"]), arr(g["RightHand"]["local_rot_xyzw"])))
    a = d["raw_data_assets"]
    sd = a["63288"]["data"]
    o.w("inline constexpr double kStandingBaseOffset = %s, kStandingForce = %s;" % (f(sd["baseOffset"]),
                                                                                    f(sd["standingForce"])))
    o.w("inline constexpr int kStandingDefault = %d;" % sd["defaultSate"])
    names = []
    for inst in sd["standingInstances"]:
        c1 = o.curve(inst["curve"], "kStandCurve%d" % inst["id"])
        c2 = o.curve(inst["bobCurve"], "kStandBob%d" % inst["id"])
        names.append("{ %d, %s, %s, %s, %s, %s }" % (inst["id"], c1, c2, f(inst["staticAngleLowering"]),
                                                    f(inst["downHillHelp"]), f(inst["UpHillHelp"])))
    o.w("struct StandDef { int id; Curve curve, bob; double sal, dhh, uhh; };")
    o.w("inline constexpr StandDef kStanding[%d]{ %s };" % (len(names), ", ".join(names)))
    o.w("struct StepDef { int id; double mn, mx; };")
    st = a["63292"]["data"]["steps"]
    o.w("inline constexpr StepDef kSteps[%d]{ %s };" % (len(st), ", ".join(
        "{ %d, %s, %s }" % (s["ID"], f(s["minTime"]), f(s["maxTime"])) for s in st)))
    mv = a["63283"]["data"]["moves"]
    o.w("struct MoveDef { int id; double force; };")
    o.w("inline constexpr MoveDef kMoves[%d]{ %s };" % (len(mv), ", ".join("{ %d, %s }" % (m["ID"], f(m["force"]))
                                                                          for m in mv)))
    o.w("inline constexpr double kGravityHandler = %s;" % f(a["63273"]["data"]["gravity"]))
    o.w("struct AJDef { int id; int useTwist; double low, high; int useY; double y; int useZ; double z; };")
    for pid in ("63279", "63280"):
        js = a[pid]["data"]["joints"]
        o.w("inline constexpr AJDef kAJ%s[%d]{ %s };" % (pid, len(js), ", ".join(
            "{ %d, %d, %s, %s, %d, %s, %d, %s }" % (e["ID"], e["useTwist"], f(e["lowTwist"]), f(e["highTwist"]),
                                                    e["useAngularY"], f(e["angularY"]), e["useAngularZ"],
                                                    f(e["angularZ"])) for e in js)))
    o.w("struct CADef { int torque; int id; std::array<double, 3> fwd, bwd; int space; Curve curve; };")
    for pid in ("63266", "63267", "63268", "63269", "63270"):
        dd = a[pid]["data"]
        ents = []
        for kind, lst in (("torque", dd.get("animations", [])), ("force", dd.get("forceAnimations", []))):
            for e in lst:
                cn = o.curve(e["curve"])
                ents.append("{ %d, %d, %s, %s, %d, %s }" % (
                    1 if kind == "torque" else 0, e["ID"], arr((e["forward"]["x"], e["forward"]["y"], e["forward"]["z"])),
                    arr((e["backward"]["x"], e["backward"]["y"], e["backward"]["z"])), e["forceType"], cn))
        o.w("inline constexpr CADef kCA%s[%d]{ %s };" % (pid, max(1, len(ents)), ", ".join(ents) if ents else "{}"))
        o.w("inline constexpr int kCA%sN = %d;" % (pid, len(ents)))
    dh = d["raw_unit_behaviours"]["DataHandler"]["data"]
    o.curve(dh["torsoAngleCurve"], "kTorsoAngleCurve")
    o.curve(d["raw_wings"]["Wings"]["data"]["flightCurve"], "kFlightCurve")
    o.curve(d["raw_bell_curve"], "kBellCurve")
    mh = d["raw_unit_behaviours"]["MovementHandler"]["data"]
    o.w("inline constexpr double kMoveLerpSpeed = %s;" % f(mh["lerpSpeed"]))
    o.w("inline constexpr double kMoveMultiplier = %s;  // MovementHandler.multiplier * blueprint movementSpeedMuiltiplier"
        % f(mh["multiplier"] * d["raw_blueprint_selected"]["movementSpeedMuiltiplier"]))
    comps = d["laws"]["curve_animation_components"]
    pid_of = {"C_Torso": "63270", "C_Arms": "63266", "C_Elbow": "63267", "C_Leg": "63269", "C_Knees": "63268"}
    o.w("struct CompDef { int rig; const CADef* ents; int n; int isRight; int invert; double uhh; };")
    order = ["Torso", "Arm_Left", "Arm_Right", "Elbow_Left", "Elbow_Right", "Leg_Left", "Leg_Right", "Knee_Left",
             "Knee_Right"]
    o.w("inline constexpr CompDef kComps[9]{ %s };" % ", ".join(
        "{ %d, kCA%s, kCA%sN, %d, %d, %s }" % (RIG_NAMES.index(n), pid_of[comps[n][0]], pid_of[comps[n][0]],
                                             comps[n][1], comps[n][2], f(comps[n][3])) for n in order))
    o.w("}")
    with open(dst, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(o.lines) + "\n")
    print("wrote", dst, len(o.lines), "lines")


if __name__ == "__main__":
    main()
